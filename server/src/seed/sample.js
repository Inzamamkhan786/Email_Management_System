function conv({
  id,
  accountId,
  clientId,
  workspaceId,
  subject,
  classification,
  priority,
  unread,
  important = false,
  archived = false,
  status = "open",
  waitingSince = null,
  lastDays,
  lastHour,
  analysis,
  messages,
  hasAttachments,
}) {
  const last = messages[messages.length - 1];
  const attachments = messages.some((m) => m.attachments?.length);
  return {
    _id: id,
    subject,
    accountId,
    clientId,
    workspaceId,
    classification,
    priority,
    unread,
    important,
    archived,
    status,
    waitingSince,
    lastMessageAt: last.sentAt || t(lastDays, lastHour),
    snippet: last.body.slice(0, 140),
    participants: uniquePeople(messages),
    hasAttachments: hasAttachments ?? attachments,
    analysis: { ...analysis, mock: true, overridden: false },
    messages: messages.map((m, i) => ({
      ...m,
      to: m.to || [],
      cc: m.cc || [],
      attachments: m.attachments || [],
      id: `${id}_m${i}`,
    })),
    tags: [],
    createdAt: messages[0].sentAt,
    updatedAt: last.sentAt,
  };
}

function uniquePeople(messages) {
  const map = new Map();
  for (const m of messages) {
    if (m.from) map.set(m.from.email, m.from);
    for (const p of m.to || []) map.set(p.email, p);
  }
  return [...map.values()];
}
